"use strict";
// Uses a private temporary bridge and data directory; never touches the live session.
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const assert = require("node:assert/strict");
const root = fs.mkdtempSync(path.join(os.tmpdir(), "nonteacher-loop-"));
process.env.AGENT_DATA = path.join(root, "data");
process.env.AGENT_BRIDGE = path.join(root, "bridge");
const store = require("../server/store");
const bridge = require("../server/bridge");
const engine = require("../server/engine");
const watcher = require("../server/watcher");

(async () => {
  const course = store.createCourse({ name: "隔离测试" });
  store.saveCard(course.id, { topic: "认识分数", stages: [] });
  const first = bridge.dispatch(store.getCourse(course.id));
  const file = bridge.files.events();
  const event = { type: "utterance", text: "同学们翻到第十二页", courseId: course.id, sessionId: first.sessionId };
  const line = JSON.stringify(event);
  fs.writeFileSync(file, line.slice(0, 12));
  assert.equal(bridge.pull(course.id).imported, 0, "incomplete line must remain unread");
  fs.appendFileSync(file, line.slice(12) + "\n");
  watcher.start(course.id);
  let attempts = 0;
  engine.complete = async () => { attempts++; if (attempts === 1) throw new Error("injected failure"); return JSON.stringify({note:"进入第十二页", speak:"先观察图形", why:"课堂引导"}); };
  await watcher.tick(course.id);
  assert.equal(watcher.status(course.id).pending, 1, "failed request stays queued");
  watcher.stop(course.id);
  watcher.start(course.id);
  await watcher.tick(course.id);
  assert.equal(watcher.status(course.id).pending, 0);
  assert.equal(store.getClassroom(course.id).events.filter(e => e.type === "utterance").length, 1);
  const advice = JSON.parse(fs.readFileSync(bridge.files.outbox(), "utf8").trim());
  assert.equal(advice.sessionId, first.sessionId);
  watcher.stop(course.id);
  const second = bridge.dispatch(store.getCourse(course.id));
  assert.notEqual(first.sessionId, second.sessionId);
  fs.appendFileSync(file, JSON.stringify({...event, sessionId:first.sessionId}) + "\n");
  assert.equal(bridge.pull(course.id).imported, 0, "old session cannot enter new session");
  assert.throws(() => bridge.appendUtterance("wrong-course", "内容"), /当前课程/);
  bridge.appendUtterance(course.id, "输入法测试");
  watcher.start(course.id);
  let secondPayload;
  engine.complete = async (args) => { secondPayload = JSON.parse(args.messages[0].content); return JSON.stringify({note:null,speak:null,why:"test"}); };
  await watcher.tick(course.id);
  assert.deepEqual(secondPayload.notesSoFar, [], "previous session observations must not be passed as current facts");
  assert.equal(store.getClassroom(course.id).events.filter(e => e.source === "external-dictation").length, 1);
  fs.appendFileSync(file, JSON.stringify({type:"class_ended", courseId:course.id, sessionId:second.sessionId}) + "\n");
  await watcher.tick(course.id);
  assert.equal(store.getClassroom(course.id).meta.state, "ended");
  assert.equal(watcher.status(course.id).running, false);
  bridge.dispatch(store.getCourse(course.id));
  bridge.appendUtterance(course.id, "较早的课堂请求");
  watcher.start(course.id);
  let resolveModel;
  engine.complete = () => new Promise(resolve => { resolveModel = resolve; });
  const inFlight = watcher.tick(course.id);
  assert.equal(typeof resolveModel, "function");
  bridge.appendUtterance(course.id, "更新的课堂请求");
  resolveModel(JSON.stringify({note:null,speak:"过时建议",why:"旧请求"}));
  await inFlight;
  assert.equal(watcher.status(course.id).pending, 1, "newer input remains queued");
  assert(!watcher.readOutbox().some(item => item.text === "过时建议"), "old advice is not pushed");
  watcher.stop(course.id);
  bridge.dispatch(store.getCourse(course.id));
  bridge.appendUtterance(course.id, "请检查长提示");
  watcher.start(course.id);
  engine.complete = async () => JSON.stringify({note:null,speak:"测试长内容请同学们先观察三条线段是否首尾相接形成封闭图形然后比较边长",why:"长文本测试"});
  await watcher.tick(course.id);
  const longTip = watcher.readOutbox().at(-1).text;
  assert.equal(Array.from(longTip).length, 24); assert(longTip.endsWith("…"));
  watcher.stop(course.id);
  console.log("PASS: partial writes, retry, deduplication, session isolation, stale response suppression and long-tip indication");
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(() => {
  fs.rmSync(root, { recursive: true, force: true });
});
