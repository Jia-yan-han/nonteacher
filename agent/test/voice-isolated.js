"use strict";
const assert = require("node:assert/strict");
const { VoiceActivityDetector } = require("../../teacher-demo/dev-work/project/src/asr");
const detector = new VoiceActivityDetector();
const speech = Buffer.alloc(640);
for (let i=0; i<640; i+=2) speech.writeInt16LE(5000, i);
const silence = Buffer.alloc(640);
let result;
for (let i=0; i<6; i++) result=detector.push(speech);
assert.equal(result.started, true);
for (let i=0; i<30; i++) result=detector.push(silence);
assert.equal(result.ended, true);
const segment = detector.takeUtterance();
assert.equal(segment.length, 36 * 640, "retains speech onset and final silence");
assert.equal(detector.takeUtterance(), null);
const leading = new VoiceActivityDetector();
const quietSyllable = Buffer.alloc(640);
for (let i=0; i<640; i+=2) quietSyllable.writeInt16LE(400, i);
for (let i=0; i<10; i++) leading.push(quietSyllable);
for (let i=0; i<6; i++) leading.push(speech);
for (let i=0; i<30; i++) leading.push(silence);
const captured = leading.takeUtterance();
assert.equal(captured.readInt16LE(0),400,"quiet audio before speech detection is preserved");
console.log("PASS: VAD retains speech onset and emits a complete utterance");
